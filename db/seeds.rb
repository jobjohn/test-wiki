# 初回起動時に作成される初期データ（既に存在する場合は何もしない）
Setting.current
User.ensure_default_admin!

home_title = ENV.fetch("WIKI_HOME_PAGE", "ホーム")

unless Page.find_by_title(home_title)
  Page.create!(
    title: home_title,
    tag_list: "はじめに",
    edit_summary: "初期ページ",
    body: <<~MARKDOWN
      Wiki へようこそ。このページは自由に編集できます（右上の「編集」ボタン）。

      ## 使い方

      - 右上の **＋ 新規ページ** からページを作成します
      - ページは **フォルダ** に分けて整理できます。フォルダの中にフォルダを作って階層化できます（左のサイドバーにツリー表示）
      - **タグ** を付けてページを分類できます
      - 編集のたびに **履歴** が残り、差分の確認や過去の版への復元ができます
      - 画面上部の検索ボックスで全文検索できます（`/` キーでフォーカス）

      詳しい書き方は [[Markdown の書き方]] を参照してください。
    MARKDOWN
  )

  Page.create!(
    title: "Markdown の書き方",
    folder: Folder.find_or_create_by!(name: "ヘルプ", parent: nil),
    tag_list: "はじめに, ヘルプ",
    edit_summary: "初期ページ",
    body: <<~'MARKDOWN'
      本文は GitHub 形式の Markdown で記述できます。

      ## 見出し

      ```markdown
      # 見出し1
      ## 見出し2
      ### 見出し3
      ```

      ## Wiki リンク

      - `[[ページ名]]` と書くと他のページへのリンクになります
      - `[[ページ名|表示名]]` で表示するテキストを変えられます
      - まだ存在しないページへのリンクは赤色で表示され、クリックするとそのページを作成できます（例: [[まだないページ]]）

      ## 装飾

      | 書き方 | 表示 |
      | --- | --- |
      | `**太字**` | **太字** |
      | `*斜体*` | *斜体* |
      | `~~取り消し線~~` | ~~取り消し線~~ |
      | `` `コード` `` | `コード` |

      ## リスト・チェックリスト

      - [x] 完了したタスク
      - [ ] 未完了のタスク

      1. 番号付き
      2. リスト

      ## コードブロック

      ```ruby
      def hello(name)
        puts "Hello, #{name}!"
      end
      ```

      ## 画像・ファイル

      編集画面のテキストエリアに画像をドラッグ＆ドロップするか、クリップボードから貼り付けると自動でアップロードされます。

      ## 脚注

      脚注も使えます[^1]。

      [^1]: これが脚注です。
    MARKDOWN
  )
end
